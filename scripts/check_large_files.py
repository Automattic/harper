#!/usr/bin/env python3
"""Fail when a large file, or a generated binary, is tracked by git.

Every byte checked in stays in the history for good. Two kinds of file do not
belong in it:

  * generated binaries, such as the German dictionary pack (`harper-german.pack`):
    they are built by `just language-bake` and by the release workflow from the
    word lists that are checked in, and they change with every dictionary edit;
  * anything over the size limit that is not on the list below.

The list is the files that were already this large when the check was added. Do not
add to it to get a change through: make the file smaller, or build it instead.

Usage: check_large_files.py [--limit-mib N]
"""

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Generated by a recipe or a workflow, never checked in.
GENERATED_SUFFIXES = (".pack",)

# Large before this check existed.
ALLOWED = {
    "harper-thesaurus/thesaurus.txt",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit-mib", type=float, default=8.0)
    limit = int(ap.parse_args().limit_mib * 1024 * 1024)

    tracked = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True
    ).stdout.decode().split("\0")

    problems = []
    for name in filter(None, tracked):
        path = ROOT / name
        if not path.is_file():  # deleted in the working tree, or a submodule
            continue
        if name.endswith(GENERATED_SUFFIXES):
            problems.append(f"{name}: a generated file; build it, do not check it in")
        elif path.stat().st_size > limit and name not in ALLOWED:
            mib = path.stat().st_size / 1024 / 1024
            problems.append(f"{name}: {mib:.1f} MiB, over the {limit / 1024 / 1024:.0f} MiB limit")

    if problems:
        print("Files that must not be checked in:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

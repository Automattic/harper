class Lexeme:
    __slots__ = ("id", "lemma", "cat", "genders", "forms", "weight")

    def __init__(self, id, lemma, cat, gender, weight=0):
        self.id, self.lemma, self.cat, self.weight = id, lemma, cat, weight
        self.genders = [GENDER[g] for g in gender.split(",")] if gender else []
        self.forms = []  # (form, frozenset(features))


def load_lexemes(path):
    db = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    lex = {}
    for i, lemma, cat, gender, claims, senses in db.execute(
        "select id, lemma, category, gender, claims, senses from lexeme"
    ):
        lex[i] = Lexeme(i, lemma, cat, gender, (claims or 0) + (senses or 0))
    for form, i, ft in db.execute("select form, lexeme_id, features from form"):
        if i in lex:
            lex[i].forms.append((form, frozenset(q for q in ft.split("|") if q)))
    return lex


class Builder:
    def __init__(self, lexemes):
        self.aff = ga.Affixes()
        self.lex = lexemes
        self.entries = {}  # headword -> set of flags
        self.stats = collections.Counter()
        self.noun_lemmas = {l.lemma for l in lexemes.values() if l.cat == "noun"}
        self.noun_forms = {f for l in lexemes.values() if l.cat == "noun" for f, _ in l.forms}
        self.noun_weight = {}
        for l in lexemes.values():
            if l.cat == "noun":
                self.noun_weight[l.lemma] = max(self.noun_weight.get(l.lemma, 0), l.weight)
        self.adj_lemmas = {l.lemma for l in lexemes.values() if l.cat == "adj"}
        self._gen_cache = {}
        self.stems = set()
        self.closed_words = {w.lower() for w, f in closed.entries().items() if set(f) & set('456P')}
        self.imperatives = set()
        self.strong_imperatives = set()
        self.verb_lemma_set = set()
        self.zu_candidates = []

    # -- helpers -------------------------------------------------------------
    def add(self, word, flags):
        if set(flags) <= {"V", "t", "%"} and word.lower() in self.closed_words:
            return  # the verb reading of `ein`, `hat`-like function words is not an entry of its own
        if not sane(word):
            self.stats["skipped-headword"] += 1
            return
        self.entries.setdefault(word, set()).update(flags)

    def generated(self, word, flags):
        """Forms `flags` generate on `word`, apart from the word itself."""
        key = (word, flags)
        if key not in self._gen_cache:
            out = set(self.aff.expand(word, flags))
            out.discard(word)
            self._gen_cache[key] = out
        return self._gen_cache[key]

    # -- nouns ---------------------------------------------------------------
    FEMININE_SUFFIXES = ("ung", "heit", "keit", "schaft", "ion", "tät", "ik", "ur", "anz", "enz", "ei", "age", "ive")
    NEUTER_SUFFIXES = ("chen", "lein", "ment", "ett", "ium", "tum")
    MASCULINE_SUFFIXES = ("ismus", "ling", "ist", "eur", "ant")
    REGULAR_PLURAL = ("ung", "heit", "keit", "schaft", "ion", "tät")

    def generated_without_inclusive(self, lemma, flag):
        """`K` and `L` also build the gender-inclusive spellings (*LehrerIn*), which no lexeme lists."""
        return {g for g in self.generated(lemma, flag) if not re.search(r"[a-zäöüß]In", g)}

    def guess_genders(self, lemma):
        if lemma.endswith(self.NEUTER_SUFFIXES):
            return ["Z"]
        if lemma.endswith(self.FEMININE_SUFFIXES):
            return ["F"]
        if lemma.endswith(self.MASCULINE_SUFFIXES):
            return ["M"]
        return []

    def noun(self, lex, proper=False):
        lemma = lex.lemma
        if " " in lemma or not sane(lemma):
            return
        if not proper:
            override = MULTI_GENDER.get(lemma.lower()) or curated.COMMON_NOUN_GENDERS.get(lemma)
            if override:
                lex.genders = list(override)
            elif not lex.genders:
                lex.genders = self.guess_genders(lemma)
        attested = {f for f, _ in lex.forms} | {lemma}
        pl_nom = {f for f, ft in lex.forms if PL in ft and NOM in ft}
        pl_any = {f for f, ft in lex.forms if PL in ft}
        sg_gen = {f for f, ft in lex.forms if SG in ft and GEN in ft}
        flags = set(lex.genders) | {"N"}
        if not proper:
            flags.add("h")
            if not self.is_compound_element(lex):
                flags.add("!")  # acronyms and short nouns few dictionaries list: not compound elements (*BGH*, *Rant*)

        def blocked(form):
            """Is `form` the lemma of a better established noun? Then that noun's entry speaks for it."""
            other = self.noun_weight.get(form)
            return form != lemma and other is not None and other >= max(6, 2 * lex.weight)

        covered = {lemma}
        for g in "0H":
            gen = self.generated(lemma, g)
            if gen and gen <= attested and gen & sg_gen:
                flags.add(g)
                covered |= gen
        plural_flagged = False
        plural_forms = set()
        for p in PLURAL_FLAGS:
            gen = self.generated_without_inclusive(lemma, p) if p == "L" else self.generated(lemma, p)
            if gen and gen <= attested and (gen & pl_nom or (p == "E" and lemma in pl_nom)) and not any(blocked(g) for g in gen):
                flags.add(p)
                covered |= gen
                plural_forms |= gen
                plural_flagged = True
        if lemma in pl_nom:
            plural_flagged = True
        if not pl_any and not proper and "F" in lex.genders:
            # nothing is attested: the derivational suffixes have only one plural
            if lemma.endswith(self.REGULAR_PLURAL):
                flags.add("Y")
                plural_forms |= self.generated(lemma, "Y")
                plural_flagged = True
            elif lemma.endswith("in") and len(lemma) > 4:
                flags.add("L")
                plural_forms |= self.generated_without_inclusive(lemma, "L")
                plural_flagged = True
        # a masculine agent noun has its feminine: Lehrer - Lehrerin, Lehrerinnen
        if not proper and "M" in lex.genders and lemma.endswith(("er", "ler", "ent", "ist", "or", "eur", "ant", "ar")):
            fem = self.generated_without_inclusive(lemma, "K")
            if fem and fem & self.noun_lemmas:
                flags.add("K")
                if self.generated_without_inclusive(lemma, "L") & self.noun_forms:
                    flags.add("L")
        self.add(lemma, flags)
        # a plural that lacks the dative -n is marked, so the dative-plural rule can find it
        for form in plural_forms:
            if not form.endswith(("n", "s")):
                self.add(form, {"&"})
        # forms the flags do not reach
        for form, ft in lex.forms:
            if form in covered or form == lemma:
                continue
            if not sane(form) or " " in form:
                continue
            if (form in self.noun_lemmas and PL not in ft) or blocked(form) or form == lemma[:-1]:
                continue  # a form that is another noun's lemma: that noun's entry says what it is
            extra = {"N"}
            if PL in ft:
                extra.add(";")
                if not form.endswith(("n", "s")):
                    extra.add("&")
            else:
                extra |= set(lex.genders)
            self.add(form, extra)
            self.stats["noun-explicit-form"] += 1
        if not plural_flagged and pl_any:
            self.add(lemma, {"A"})
        elif not pl_any and not plural_flagged and len(lex.forms) >= 3:
            self.add(lemma, {"A"})

    # -- verbs ---------------------------------------------------------------
    SEPARABLE = ("ab an auf aus bei dar ein empor entgegen fort frei heim her hin hinzu los mit nach nieder statt "
                 "teil vor voran voraus vorbei vorüber weg weiter wieder zu zurück zusammen zuvor herbei heraus "
                 "herein herauf herunter hinaus hinein hinauf hinunter dazu hervor umher bereit fertig fest "
                 "gegen gleich klar kaputt offen still tot zugrunde zunichte zurecht fehl hoch nieder rück "
                 "vorher vorweg weiter zwischen wider mit").split()
    EITHER = "über unter um durch hinter wider voll".split()
    INSEPARABLE = "be ent er ge ver zer emp miss".split()

    def verb_rich(self, lex):
        """A verb whose paradigm Wikidata lists: flags are the ones it confirms."""
        lemma = lex.lemma
        attested = {f for f, _ in lex.forms if " " not in f} | {lemma}
        flags = {"V"}
        covered = {lemma}
        present = any(PRESENT in ft and " " not in f for f, ft in lex.forms)
        preterite = any(PRETERITE in ft and " " not in f for f, ft in lex.forms)
        pp_forms = [f for f, ft in lex.forms if PARTICIPLE2 in ft and " " not in f]
        strong_pp = any(not f.endswith(("t", "et")) for f in pp_forms) and lemma not in curated.WEAK_AND_STRONG
        for f in VERB_FLAGS:
            gen = self.generated(lemma, f)
            if not gen:
                continue
            unattested_tense = not (present if f in "fijG" else preterite) and not (f in "de" and strong_pp)
            if gen <= attested or unattested_tense:
                flags.add(f)
                covered |= gen
        part1 = {f for f, ft in lex.forms if PARTICIPLE1 in ft}
        gen = self.generated(lemma, "c")
        if part1 and part1 & gen:
            flags.add("c")
            covered |= gen
        flags.add("j")
        irregular, pp = [], set()
        done_pret_stems = set()
        for form, ft in lex.forms:
            if " " in form:
                parts = form.split(" ")
                if len(parts) == 2 and ft and PARTICIPLE2 not in ft and ZU_INFINITIVE not in ft and sane(parts[0]):
                    if IMPERATIVE in ft and SG in ft and not parts[0].endswith("e") and not strong_pp and lex.weight < 8:
                        continue  # *ahm nach*: the bare stem of a weak verb is not a word
                    if lemma.startswith(parts[1]) and lemma[len(parts[1]):] not in self.all_verb_lemmas:
                        continue  # *petern herum*: there is no verb *petern* for the head to be a form of
                    irregular.append((parts[0], {"V"}))
                continue
            if not sane(form):
                continue
            if PARTICIPLE2 in ft:
                pp.add(form)
            elif form in covered:
                continue
            elif PARTICIPLE1 in ft:
                irregular.append((form, {"J", "O", "Q", "R", "S", "T"}))
            else:
                extra = {"V"}
                if IMPERATIVE in ft and SG in ft and not form.endswith("e"):
                    if not strong_pp and lex.weight < 8:
                        continue  # *ahm*: the bare stem of a rare weak verb is a compound element, not a word
                    extra.add("imp")  # *sag*, *lies*: added only if no other word has the spelling
                if PRETERITE in ft or SUBJ2 in ft:
                    extra.add("t")
                if strong_pp and ((PRESENT in ft and SG in ft and ft & {P2, P3} and INDICATIVE in ft) or (IMPERATIVE in ft and SG in ft)):
                    extra.add("%")
                if PRETERITE in ft and SG in ft and ft & {P1, P3} and form not in done_pret_stems:
                    gen = self.generated(form, "s")
                    if gen and gen <= attested:
                        extra.add("s")
                        covered |= gen
                        done_pret_stems.add(form)
                irregular.append((form, extra))
        if not pp and "d" in flags:
            pp.add(self.pp_regular(lemma))
        return {"flags": flags, "irregular": irregular, "pp": pp}

    def pp_regular(self, lemma):
        """The past participle of a weak verb: `lernen` -> `gelernt`."""
        for p in sorted(self.SEPARABLE, key=len, reverse=True):
            if lemma.startswith(p) and len(lemma) - len(p) >= 4:
                return p + self.pp_regular(lemma[len(p):])
        stem = lemma[:-2] if lemma.endswith("en") else lemma[:-1]
        if lemma.endswith(("ieren", "ieren")) or any(lemma.startswith(i) for i in self.INSEPARABLE if len(lemma) > len(i) + 3):
            prefix = ""
        else:
            prefix = "ge"
        needs_e = stem.endswith(("t", "d")) or (len(stem) > 1 and stem[-1] in "mn" and stem[-2] not in "aeiouäöüälrh")
        return prefix + stem + ("et" if needs_e else "t")

    def derive_verb(self, lemma, known):
        """The inflection of `lemma` copied from the verb it is built on, if any."""
        for p in sorted(self.SEPARABLE + self.EITHER + self.INSEPARABLE, key=len, reverse=True):
            base = lemma[len(p):]
            if lemma.startswith(p) and len(base) >= 4 and base in known and known[base].get("rich"):
                b = known[base]
                sep = p in self.SEPARABLE or p in self.EITHER
                insep = p in self.INSEPARABLE or p in self.EITHER
                irregular = []
                for form, extra in b["irregular"]:
                    irregular.append((p + form, set(extra)))
                    if sep and p in self.SEPARABLE and "V" in extra and "J" not in extra:
                        irregular.append((form, set(extra)))
                pp = set()
                for form in b["pp"]:
                    if sep:
                        pp.add(p + form)
                    if insep:
                        pp.add(p + (form[2:] if form.startswith("ge") else form))
                if not b["pp"]:
                    pp.add(self.pp_regular(lemma))
                if sep:
                    irregular.append((p + "zu" + base, {"V"}))
                return {"flags": set(b["flags"]), "irregular": irregular, "pp": pp, "rich": False}
        return None

    def strong_info(self, inf, pret, pp, sg3):
        """The paradigm of a strong or irregular verb from the hand-written table."""
        flags = {"V", "f", "j", "i", "c"}
        irregular = []
        stem = inf[:-2] if inf.endswith("en") and not inf.endswith(("ern", "eln")) else inf[:-1]
        if pret.endswith("te"):  # mixed verbs: brennen - brannte, bringen - brachte
            base = pret[:-1]
            for e in ("e", "est", "en", "et"):
                irregular.append((base + e, {"V", "t"}))
        else:
            irregular.append((pret, {"V", "t", "s"}))
            subjunctive = closed.umlaut(pret)
            for e in ("e", "est", "et", "en"):
                irregular.append((subjunctive + e, {"V", "t"}))
        if sg3:
            irregular.append((sg3, {"V", "%"}))
            if sg3.endswith("t") and stem[-1] not in "td":
                sg2 = sg3[:-1] + "st"
            elif sg3.endswith("st"):
                sg2 = sg3
            elif sg3.endswith(("ß", "s", "x", "z")):
                sg2 = sg3 + "t"
            elif sg3 == "wird":
                sg2 = "wirst"
            elif sg3.endswith("t"):
                sg2 = sg3 + "st"
            else:
                sg2 = sg3 + "st"
            irregular.append((sg2, {"V", "%"}))
            if "ä" not in sg3 and "äu" not in sg3 and sg3.endswith("t") and sg3 not in ("tut", "hat"):
                irregular.append((sg3[:-1], {"V", "%"}))  # gib, lies, nimm
            elif "ä" in sg3:
                irregular.append((stem, {"V", "imp"}))
        else:
            flags.add("G")
            irregular.append((stem, {"V", "imp"}))
        return {"flags": flags, "irregular": irregular, "pp": {pp}, "rich": True}

    def strong_table(self):
        table = {}
        for row in curated.STRONG_VERBS:
            parts = row.split()
            table[parts[0]] = self.strong_info(parts[0], parts[1], parts[2], parts[3] if len(parts) > 3 else "")
        return table

    def verbs(self, lexemes):
        have = {l.lemma for l in lexemes}
        lexemes = list(lexemes) + [
            Lexeme("x" + v, v, "verb", None, 0) for v in curated.EXTRA_VERBS if v not in have
        ]
        self.all_verb_lemmas = {l.lemma for l in lexemes} | {row.split()[0] for row in curated.STRONG_VERBS}
        known = {}
        sparse = []
        table = self.strong_table()
        seen = set()
        for lex in lexemes:
            lemma = lex.lemma
            if " " in lemma or not sane(lemma) or not lemma.endswith("n"):
                continue
            seen.add(lemma)
            finite = [f for f, ft in lex.forms if " " not in f and INFINITIVE not in ft and PARTICIPLE2 not in ft]
            if len(finite) >= 8:
                info = self.verb_rich(lex)
                info["rich"] = True
                known.setdefault(lemma, info)
                self.emit_verb(lemma, info, lex)
            else:
                sparse.append(lex)
        for inf, info in table.items():
            known.setdefault(inf, info)
        for lex in sorted(sparse, key=lambda l: len(l.lemma)):
            lemma = lex.lemma
            info = table.get(lemma) or self.derive_verb(lemma, known)
            if info:
                self.stats["verb-derived"] += 1
            else:
                stem = lemma[:-2] if lemma.endswith("en") and not lemma.endswith(("ern", "eln")) else lemma[:-1]
                info = {"flags": {"V", "f", "i", "G", "j", "d", "e", "c"},
                        "irregular": [(stem, {"V", "imp"})] if lex.weight >= 8 else [],
                        "pp": {self.pp_regular(lemma)}, "rich": False}
                pp_seen = {f for f, ft in lex.forms if PARTICIPLE2 in ft and " " not in f}
                if any(p.endswith("en") for p in pp_seen):
                    info["flags"] -= {"d", "e"}
                    info["pp"] = set()
                self.stats["verb-default-weak"] += 1
            known.setdefault(lemma, info)
            own = self.verb_rich(lex)
            info = {"flags": info["flags"], "irregular": info["irregular"] + own["irregular"], "pp": info["pp"] | own["pp"]}
            self.emit_verb(lemma, info, lex)
        # strong verbs Wikidata has no lexeme for at all, and the verbs built on them
        for inf, info in table.items():
            if inf not in seen:
                self.stats["verb-from-table"] += 1
                self.emit_verb(inf, info, None)

    def emit_verb(self, lemma, info, lex):
        flags = set(info["flags"])
        if lemma.endswith("en") or lemma.endswith(("ern", "eln")):
            self.stems.add(lemma[:-2] if lemma.endswith("en") and not lemma.endswith(("ern", "eln")) else lemma[:-1])
        if self.generated(lemma, "c"):
            flags.add("c")
        gen = self.generated(lemma, "x")
        if gen and (any(g in self.adj_lemmas for g in gen) or lemma.endswith("ieren")):
            flags.add("x")
        self.add(lemma, flags)
        self.verb_lemma_set.add(lemma)
        for prefix in self.SEPARABLE:
            rest = lemma[len(prefix):]
            if lemma.startswith(prefix) and len(rest) >= 4 and rest.endswith("n"):
                self.zu_candidates.append((prefix, rest, lemma))
                break
        for form, extra in info["irregular"]:
            if "imp" in extra:
                self.imperatives.add(form)  # added later, unless it is a word of another class
                if "%" in extra:
                    self.strong_imperatives.add(form)
            else:
                self.add(form, extra)
        finite = self.generated(lemma, "".join(f for f in flags if f in "defGij")) | {f for f, _ in info["irregular"]}
        for form in info["pp"]:
            if form in finite:
                # *agiert* is the participle and the third person: the declined forms are entries of their
                # own, so that the finite form is not an adjective as well
                self.add(form, {"V", "g"})
                for declined in self.aff.expand(form, "OQRST"):
                    if declined != form:
                        self.add(declined, {"J"})
            else:
                self.add(form, {"V", "g", "O", "Q", "R", "S", "T"})

    # -- adjectives ----------------------------------------------------------
    def adjective(self, lex):
        lemma = lex.lemma
        if " " in lemma or not sane(lemma):
            return
        attested = {f for f, _ in lex.forms}
        comps = {f for f, ft in lex.forms if COMPARATIVE in ft}
        sups = {f for f, ft in lex.forms if SUPERLATIVE in ft}
        flags = {"J", "q", "r", "O", "Q", "R", "S", "T"}
        # comparative and superlative: the flag when it reproduces what is attested,
        # an entry of its own when it does not
        regular_comp = bool(comps) and comps <= {lemma + "er", lemma + "r", lemma[:-2] + "ler" if lemma.endswith("el") else lemma + "er"}
        if comps and not regular_comp or comps and not any(c in self.generated(lemma, "S") | {lemma + "er"} for c in comps):
            regular_comp = False
        if regular_comp and self.generated(lemma, "U"):
            flags.add("U")
        else:
            for c in comps:
                if sane(c) and c != lemma:
                    self.add(c, {"J", "O", "Q", "R", "S", "T"})
        sup_ok = False
        if sups:
            gen = self.generated(lemma, "W")
            if gen and all(any(g.endswith(s[-2:]) for g in gen) for s in sups) and sups & gen:
                sup_ok = True
        if sup_ok:
            flags.add("W")
        else:
            for s in sups:
                if sane(s) and s.endswith("en"):
                    self.add(s[:-2], {"J", "O", "Q", "R", "S", "T"})
        if lex.weight >= 10 and "U" not in flags:
            flags |= {"U"}  # the adjectives every dictionary lists are gradable: *bekanntesten*, *häufigsten*
        if lex.weight >= 10 and not sup_ok:
            flags |= {"W"}
        self.add(lemma, flags)
        for form, ft in lex.forms:
            if form in (lemma,) or form in comps or form in sups or not sane(form):
                continue
            self.add(form, {"J"})

    def nominalized(self, lex):
        """*das Wesentliche*, *die Deutschen*: any adjective can be written as a noun. For the adjectives
        every dictionary lists, the capitalized forms are entries of their own, so that the lower-case
        spelling carries the noun reading too and the capitalization rule can see it."""
        lemma = lex.lemma
        if lex.weight < 9 or len(lemma) < 5 or not lemma.isalpha() or not lemma.islower():
            return
        capitalized = lemma[0].upper() + lemma[1:]
        for form in self.aff.expand(capitalized, "OQRST"):
            if form == capitalized or form in self.noun_lemmas or form in self.noun_forms:
                continue  # *Breite*, *Angehörige*: a noun the list has already says what it is
            # *der/die/das Deutsche*: the ending says which genders the noun can have
            genders = {"e": "MFZ", "es": "Z", "em": "MZ", "er": "MF"}.get(form[len(capitalized):], "")
            if not genders and form.endswith("e"):
                genders = "MFZ"  # the stem itself ends in -e: *Müde* + e
            self.add(form, {"N"} | set(genders))
            self.stats["nominalized-form"] += 1

    # -- the rest ------------------------------------------------------------
    def simple(self, lex, flags):
        if not sane(lex.lemma):
            return
        if flags == {"P"} and lex.lemma[0].islower() and lex.lemma[0].upper() + lex.lemma[1:] in curated.NOUN_AND_FUNCTION_WORD_SET:
            # *Dank* / *dank*, *Zeit* / *zeit*: the noun is the reading that matters for spelling and
            # capitalization; the preposition is known to the preposition rule by itself
            self.stats["function-reading-dropped"] += 1
            return
        self.add(lex.lemma, flags)
        for form, ft in lex.forms:
            if sane(form) and form != lex.lemma:
                self.add(form, flags)

    def derivational_adjective(self, lex):
        """Wikidata lists `westlich` as adverb and preposition; it declines as an adjective too."""
        if lex.lemma.endswith(ADJECTIVE_SUFFIXES) and len(lex.lemma) > 6 and lex.lemma[0].islower():
            self.add(lex.lemma, {"J", "q", "O", "Q", "R", "S", "T"})

    def lexeme_emitted(self, lex):
        """Wikidata lexemes that are words of the language but so rare that they only lend a common word a
        second reading (*karten* makes *Karten* a verb, *fehl* makes *fehlen* an adjective)."""
        return (lex.lemma, lex.cat) not in curated.RARE_LEXEMES

    def other_weight(self, form, cat):
        return max((w for c, w in self.form_weights.get(form, ()) if c != cat), default=0)

    def noun_emitted(self, lex):
        """Does the word list get this noun at all? (`function_lower` is set in `build`.)"""
        if lex.lemma.lower() in self.function_lower or lex.lemma in curated.NOT_NOUNS:
            return False
        if (lex.lemma, "noun") in curated.RARE_LEXEMES:
            return False
        if (
            len(lex.lemma) <= 4
            and self.noun_weight.get(lex.lemma, 0) < 4
            and lex.lemma not in curated.COMMON_NOUN_GENDERS
            and lex.lemma not in curated.NOUN_AND_FUNCTION_WORD_SET
        ):
            return False  # *Ahr*, *Rant*: a short noun almost no dictionary lists is as likely a typo as a word
        return not (len(lex.forms) <= 2 and self.richest[lex.lemma] >= 6)

    def is_compound_element(self, lex):
        """May the noun act as a compound element? Acronyms and short nouns few dictionaries list may not (flag `!`)."""
        if len(lex.lemma) >= 2 and lex.lemma.isupper():
            return False
        return True

    # -- compounds -----------------------------------------------------------
    INTERFIXES = ("", "s", "n", "en", "er", "es")
    S_ONLY_SUFFIXES = ("ung", "heit", "keit", "schaft", "ion", "tät")

    def load_begin_forms(self):
        path = HERE.parent / "compound_begin_forms.txt"
        self.begin = set()
        if path.exists():
            self.begin = {l for l in path.read_text(encoding="utf-8").splitlines() if l and not l.startswith("#")}

    def prune_compounds(self, keep=frozenset()):
        """Ids of the noun lexemes Harper's compound checker will accept anyway.

        `dictionary.dict` does not list a compound whose elements are in it and
        whose forms are the forms of its last element behind the same prefix:
        `CompoundChecker` builds it, and takes its gender and number from the
        head. This is what keeps the word list at the size of the vocabulary
        instead of the size of everything German has ever put together.
        """
        self.load_begin_forms()
        elements = set()
        for l in self.lex.values():
            if l.cat in ("adj", "adv", "prep", "conj") and l.lemma.isalpha():
                elements.add(l.lemma.lower())
            elif l.cat == "verb" and l.lemma.endswith("n") and len(l.lemma) > 4:
                elements.add(l.lemma[:-2] if l.lemma.endswith("en") and not l.lemma.endswith(("ern", "eln")) else l.lemma[:-1])
        for w, f in closed.entries().items():
            if "P" in f or "r" in f:
                elements.add(w.lower())
        noun_forms = collections.defaultdict(set)   # lowercase lemma -> forms (lowercase)
        noun_gender = collections.defaultdict(set)
        nouns = [
            l for l in self.lex.values()
            if l.cat == "noun" and sane(l.lemma) and " " not in l.lemma and l.lemma.replace("-", "").isalpha()
            and self.noun_emitted(l)
        ]
        nouns.sort(key=lambda l: (len(l.lemma), l.lemma))
        dropped = set()
        noun_elements = set()
        by_lemma = collections.defaultdict(list)
        for l in nouns:
            by_lemma[l.lemma].append(l)

        def segmentations(w):
            """Last kept noun element for each way to cut `w` into elements."""
            n = len(w)
            # reach[i]: ways to cover w[:i]; each way is a (last_noun_start | None) marker
            reach = [set() for _ in range(n + 1)]
            reach[0].add(None)
            for i in range(n):
                if not reach[i]:
                    continue
                for j in range(i + 3, n + 1):
                    piece = w[i:j]
                    is_noun = piece in noun_elements
                    if not is_noun and piece not in elements:
                        continue
                    if j == n:
                        if is_noun:
                            yield i
                        continue
                    for link in self.INTERFIXES:
                        k = j + len(link)
                        if k >= n or w[j:k] != link:
                            continue
                        if link and not is_noun:
                            continue
                        if link and piece[-1] == link[0]:
                            continue
                        if link and piece.endswith(self.S_ONLY_SUFFIXES) and link != "s":
                            continue
                        if self.begin and any((piece + l) in self.begin for l in ("", "s", "n", "en", "er", "es", "e", "ns")) and (piece + link) not in self.begin:
                            continue
                        reach[k].add(i)
            return

        for l in nouns:
            w = l.lemma.lower()
            lemmas = by_lemma[l.lemma]
            drop = False
            if (
                len(w) >= 7
                and self.noun_weight.get(l.lemma, 0) < 9  # words in many dictionaries are entries, whatever they are made of
                and l.lemma not in keep
                and l.lemma not in curated.COMMON_NOUN_GENDERS
                and w not in MULTI_GENDER
                and l.lemma[0].isupper()
            ):
                for start in segmentations(w):
                    head = w[start:]
                    prefix = w[:start]
                    if len(head) < 3 or head not in noun_gender and head not in noun_forms:
                        continue
                    hg = noun_gender[head]
                    wg = {g for g in l.genders}
                    if wg and hg and wg != hg:
                        continue
                    if wg and not hg:
                        continue
                    forms = {f.lower() for f, _ in l.forms if " " not in f}
                    if all(f.startswith(prefix) and f[len(prefix):] in noun_forms[head] for f in forms):
                        drop = True
                        break
            if drop:
                dropped.add(l.id)
            else:
                if self.is_compound_element(l):
                    noun_elements.add(w)
                noun_gender[w] |= set(l.genders)
                noun_forms[w] |= {f.lower() for f, _ in l.forms} | {w}
        self.stats["compounds-dropped"] = len(dropped)
        return dropped

    def curated_entries(self):
        for word, flags, _ in curated.ABBREVIATIONS:
            self.add(word, set(flags.replace("~", "")))
        for word, _ in curated.PERIOD_ABBREVIATIONS:
            self.add(word, {"2"})
        for word in curated.MORE_PERIOD_ABBREVIATIONS:
            self.add(word, {"2"})
        for word in curated.UNITS:
            self.add(word, {"2"})
        for word in curated.FOREIGN_TERMS:
            self.add(word, {"3"})
        for word in curated.PLURALIA_TANTUM:
            self.add(word, {"N", "+", "h"})
            self.entries[word].discard("A")
        for word in curated.GIVEN_NAMES + curated.PLACES + curated.BRANDS + curated.PERSONS + curated.FAMILY_NAMES + curated.MORE_PLACES:
            if self.entries.get(word.lower(), set()) & self.NON_NOUN_FLAGS:
                continue  # *Lang*, *Klein*, *Braun*: the adjective already has the spelling
            self.add(word, {"N", "H"})
        for word, gender in curated.GEO_GENDERS.items():
            self.add(word, {"N", "H", gender})
        for word in curated.EXTRA_VERB_FORMS:
            self.add(word, {"V", "g"})
        for word in curated.LATIN_PLURALS:
            self.add(word, {"N", ";"} | ({"&"} if not word.endswith(("n", "s")) else set()))
        for word in curated.EXTRA_ADJECTIVES:
            self.add(word, {"J", "q", "r", "O", "Q", "R", "S", "T", "U", "W"})

    def build(self, keep=frozenset()):
        self.richest = collections.defaultdict(int)
        self.form_weights = collections.defaultdict(set)
        for lex in self.lex.values():
            if lex.cat == "noun":
                self.richest[lex.lemma] = max(self.richest[lex.lemma], len(lex.forms))
            self.form_weights[lex.lemma.lower()].add((lex.cat, lex.weight))
            if lex.cat in ("noun", "adv", "prep", "conj"):
                for f, _ in lex.forms:
                    self.form_weights[f.lower()].add((lex.cat, lex.weight))
        self.function_lower = {w.lower() for w, f in closed.entries().items() if set(f) & set("456P")}
        self.function_lower |= {l.lemma.lower() for l in self.lex.values() if l.cat in ("adv", "prep", "conj", "Q126473")}
        self.function_lower -= {w.lower() for w in curated.NOUN_AND_FUNCTION_WORD}
        self.verbs([l for l in self.lex.values() if l.cat == "verb" and self.lexeme_emitted(l)])
        dropped = set() if getattr(self, "no_prune", False) else self.prune_compounds(keep)
        self.dropped = [self.lex[i].lemma for i in dropped]
        for lex in self.lex.values():
            if lex.id in dropped:
                continue
            if lex.cat == "noun" and not self.noun_emitted(lex):
                self.stats["noun-skipped"] += 1
                continue
            if lex.cat != "noun" and not self.lexeme_emitted(lex):
                continue
            c = lex.cat
            if c == "noun":
                self.noun(lex)
            elif c == "propn":
                self.noun(lex, proper=True)
            elif c == "verb":
                pass
            elif c == "adj":
                if self.lexeme_emitted(lex):
                    self.adjective(lex)
                    self.nominalized(lex)
            elif c == "adv":
                self.simple(lex, {"r"})
                self.derivational_adjective(lex)
            elif c == "prep":
                self.simple(lex, {"P"})
                self.derivational_adjective(lex)
            elif c == "Q126473":
                self.simple(lex, {"P", "4"})
            elif c == "conj":
                self.simple(lex, {"6"})
            elif c == "interj":
                self.simple(lex, set())
            elif c in DETERMINERS:
                self.simple(lex, {"4"})
            elif c in PRONOUNS:
                self.simple(lex, {"5"})
            elif c == "contraction":  # Q184943: modal particles and the like
                self.simple(lex, {"r"})
            else:
                self.stats[f"unused-category:{c}"] += 1
        for word, flags in closed.entries().items():
            if word[0].islower() and word[0].upper() + word[1:] in curated.NOUN_AND_FUNCTION_WORD_SET:
                flags = set(flags) - set("P")  # *dank*, *zeit*: the noun reading is the one that matters
                if not flags:
                    continue
            self.add(word, flags)
        self.compound_index = collections.defaultdict(list)
        for l in self.lex.values():
            if l.cat == "noun" and l.lemma.isalpha() and len(l.lemma) >= 8:
                self.compound_index[l.lemma.lower()[:3]].append(l.lemma.lower())
        self.apocope_stems()
        self.curated_entries()
        self.add_zu_infinitives()
        self.add_stems()
        self.names()
        self.mark_lowercase_twins()

    NON_NOUN_FLAGS = set("VJrP456")
    TWIN_FLAGS = set("P456")  # function words: the lower-case spelling is never the noun

    def names(self):
        """Proper names from Wikidata items, apart from those that are also function words."""
        path = HERE.parent / "wikidata_names.tsv"
        if not path.exists():
            return
        known = {w.lower() for w in self.entries}
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line or line.startswith("#"):
                continue
            name, _, kind = line.partition("\t")
            if name in self.entries or name.lower() in known:
                self.stats["name-skipped"] += 1  # already a word: the name adds nothing but a flag to it
                continue
            flags = {"N", "H", "!"}  # never an element of a compound: *Annfang* is not *Ann* + *fang*
            self.add(name, flags)
            self.stats["name"] += 1

    def apocope_stems(self):
        """*Farb|fernseher*, *Erd|geschichte*: a noun in *-e* loses the *e* in front of some compounds.

        The compounds are the Wikidata noun lemmas; a stem is recorded when the noun without its *e* is
        followed by another noun of the list."""
        lower = {l.lemma.lower() for l in self.lex.values() if l.cat == "noun" and l.lemma.isalpha()}
        for noun in sorted(lower):
            if noun.endswith("e") and len(noun) >= 5:
                stem = noun[:-1]
                if stem in lower:
                    continue
                if any(c.startswith(stem) and c[len(stem):] in lower and len(c) > len(stem) + 3 for c in self.compound_index.get(stem[:3], ())):
                    self.stems.add(stem)
                    self.stats["apocope-stem"] += 1

    def add_zu_infinitives(self):
        """*anzustreichen*: the *zu* of a separable verb stands between prefix and verb."""
        for prefix, rest, lemma in self.zu_candidates:
            if rest in self.verb_lemma_set:
                self.add(prefix + "zu" + rest, {"V"})
                self.stats["zu-infinitive"] += 1

    def add_stems(self):
        """Bare verb stems, which compounds are built on (`Schreib|tisch`) but which are not words.

        A stem that is also a word (`spiel`, `hat`) needs no entry: the word is
        already a compound element, and a `*` on it would take the word out."""
        known = {w.lower() for w in self.entries}
        for form in sorted(self.imperatives):
            if form.lower() not in known and sane(form):
                self.entries[form] = {"V", "%"} if form in self.strong_imperatives else {"V"}
                self.stats["imperative"] += 1
        known = {w.lower() for w in self.entries}
        evidence = collections.Counter()
        lower = {l.lemma.lower() for l in self.lex.values() if l.cat == "noun" and l.lemma.isalpha()}
        for noun in lower:
            for cut in range(3, len(noun) - 2):
                if noun[:cut] in self.stems and noun[cut:] in lower:
                    evidence[noun[:cut]] += 1
        for stem in sorted(self.stems):
            if evidence[stem] < 2:
                continue  # a stem nobody builds a compound on is no compound element, only a way to say *Bettrieb*
            if len(stem) >= 3 and stem not in known and sane(stem):
                self.entries[stem] = {"*"}
                self.stats["stem"] += 1

    def mark_lowercase_twins(self):
        """`ist` and das `Ist`: the lower-case spelling is not the noun (flag `^`).

        Only for the words whose lower-case spelling is overwhelmingly the verb: the modals and the
        copula. Any other word that has a noun twin is read from its context."""
        for word, flags in list(self.entries.items()):
            if word in curated.LOWERCASE_ONLY and "N" not in flags:
                twin = self.entries.get(word[0].upper() + word[1:])
                if twin and "N" in twin:
                    flags.add("^")
                    self.stats["lowercase-twin"] += 1

    def write(self, path):
        lines = [HEADER]
        for word in sorted(self.entries, key=lambda w: (w.casefold(), w)):
            flags = "".join(sorted(self.entries[word]))
            lines.append(f"{word}/~~{flags}\n")
        pathlib.Path(path).write_text("".join(lines), encoding="utf-8")
        return len(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lexemes", required=True)
    ap.add_argument("--out", default=str(DICT))
    ap.add_argument("--no-prune", action="store_true", help="keep every compound in the word list")
    ap.add_argument("--keep", help="file of compound lemmas that must stay in the word list")
    ap.add_argument("--dropped", help="write the compounds left to the compound checker to this file")
    args = ap.parse_args()
    b = Builder(load_lexemes(args.lexemes))
    keep = frozenset(pathlib.Path(args.keep).read_text(encoding="utf-8").split()) if args.keep else frozenset()
    b.no_prune = args.no_prune
    b.build(keep)
    if args.dropped:
        pathlib.Path(args.dropped).write_text("\n".join(sorted(b.dropped)) + "\n", encoding="utf-8")
    n = b.write(args.out)
    print(n, "entries")
    for k, v in sorted(b.stats.items()):
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()

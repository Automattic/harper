/**
 * The harper.js API reference: the HTML files `packages/harper.js/docs.sh` generates.
 *
 * The site stores each file's body and serves it at /docs/harperjs/ref/<file>.
 */

import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

export const REFERENCE_URL = '/docs/harperjs/ref/';

export function readReference(directory) {
	return readdirSync(directory)
		.filter((file) => file.endsWith('.html'))
		.sort()
		.map((file) => parseReferenceFile(file, readFileSync(path.join(directory, file), 'utf8')));
}

export function parseReferenceFile(file, source) {
	const title = source.match(/<title>([^<]*)<\/title>/)?.[1];
	const body = source.match(/<body[^>]*>([\s\S]*)<\/body>/)?.[1];

	if (title === undefined || body === undefined) {
		throw new Error(`${file}: not a page generated by docs.sh`);
	}

	return {
		file,
		title: title.trim(),
		// The files link to each other relatively, which breaks when the index is opened as
		// /docs/harperjs/ref with no trailing slash.
		content: body.trim().replace(/href="\.\/([^"]+)"\s*>/g, `href="${REFERENCE_URL}$1">`),
	};
}
